"""Массовое наполнение баз всех фракций HelpeRP."""


def _reg(category, rid, title, text, punishment, frequent, keywords, usable_by=None):
    entry = {
        "category": category,
        "id": rid,
        "title": title,
        "description": text,
        "is_frequent": frequent,
        "keywords": keywords,
    }
    if punishment:
        entry["punishment"] = punishment
    if usable_by:
        entry["usable_by"] = usable_by
    return entry


def _d(items):
    return [{"short": s, "full": f, "is_frequent": freq} for s, f, freq in items]


