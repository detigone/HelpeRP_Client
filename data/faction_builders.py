def _reg(category, rid, title, text, punishment, frequent, keywords, usable_by=None):
    entry = {
        "category": category,
        "id": rid,
        "title": title,
        "description": text,
        "is_frequent": frequent,
        "keywords": keywords,
    }
    if punishment:
        entry["punishment"] = punishment
    if usable_by:
        entry["usable_by"] = usable_by
    return entry


def _proto(category, pid, title, protocol, frequent, keywords, usable_by=None):
    return _reg(category, pid, title, protocol, None, frequent, keywords, usable_by)


