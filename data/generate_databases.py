    files = {
        "legislation_rf.json": build_legislation,
        "mchs.json": build_mchs,
        "smp.json": build_smp,
        **BUILDERS,
    }
    for name, builder in files.items():
        path = os.path.join(BASE_DIR, name)
        data = builder()
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=4)
        count = (
            data.get("total_articles")
            or data.get("total_protocols")
            or data.get("total_entries")
            or 0
        )
        print(f"OK: {name} ({count} entries)")


