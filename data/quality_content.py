def regs_to_protocols(regs):
    """Конвертация _reg-записей в формат protocol_entry для МЧС/СМП."""
    out = []
    for r in regs:
        out.append({
            "category": r["category"],
            "id": r["id"],
            "title": r["title"],
            "protocol": r["description"],
            "is_frequent": r.get("is_frequent", True),
            "usable_by": r.get("usable_by", []),
            "keywords": r.get("keywords", []),
        })
    return out


